import streamlit as st

st.title("🏭 نظام التخصيم - مصنع الألوميتال")

# =========================
# إدخال بيانات الوحدة (فاضي)
# =========================
عرض = st.text_input("عرض الوحدة (سم)")
ارتفاع = st.text_input("ارتفاع الوحدة (سم)")
عمق = st.text_input("عمق الوحدة (سم)")

# =========================
# الأرفف
# =========================
عرض_الرف = st.text_input("عرض الرف (سم)")
عمق_الرف = st.text_input("عمق الرف (سم)")
عدد_الأرفف = st.text_input("عدد الأرفف")

# =========================
# الفواصل
# =========================
ارتفاع_الفاصل = st.text_input("ارتفاع الفاصل (سم)")
عمق_الفاصل = st.text_input("عمق الفاصل (سم)")
عدد_الفواصل = st.text_input("عدد الفواصل")

# =========================
# الأدراج
# =========================
عرض_الدرج = st.text_input("عرض الدرج (سم)")
عمق_الدرج = st.text_input("عمق الدرج (سم)")
عدد_الأدراج = st.text_input("عدد الأدراج")

# =========================
# زر الحساب
# =========================
if st.button("احسب التخصيم"):

    # التأكد من البيانات
    if عرض and ارتفاع and عمق:

        عرض = float(عرض)
        ارتفاع = float(ارتفاع)
        عمق = float(عمق)

        العرض_الصافي = عرض - 5
        الارتفاع_الصافي = ارتفاع - 13
        العمق_الصافي = عمق - 5

        st.subheader("📌 التخصيم الأساسي")
        st.write("العرض:", العرض_الصافي)
        st.write("الارتفاع:", الارتفاع_الصافي)
        st.write("العمق:", العمق_الصافي)

        # =========================
        # الأرفف
        # =========================
        if عرض_الرف and عمق_الرف and عدد_الأرفف:

            عرض_رف = float(عرض_الرف)
            عمق_رف = float(عمق_الرف)
            عدد = int(عدد_الأرفف)

            st.subheader("📚 الأرفف")
            st.write("رف:", عرض_رف - 5, "×", عمق_رف - 5, "×", عدد)

        # =========================
        # الفواصل
        # =========================
        if ارتفاع_الفاصل and عمق_الفاصل and عدد_الفواصل:

            st.subheader("🧱 الفواصل")
            st.write("فاصل:", float(ارتفاع_الفاصل), "×", float(عمق_الفاصل) - 5, "×", int(عدد_الفواصل))

        # =========================
        # الأدراج
        # =========================
        if عرض_الدرج and عمق_الدرج and عدد_الأدراج:

            st.subheader("🗄️ الأدراج")
            st.write("درج:", float(عرض_الدرج) - 2.5, "×", float(عمق_الدرج), "×", int(عدد_الأدراج))

    else:
        st.error("من فضلك ادخل بيانات الوحدة الأساسية")

import streamlit as st
import pandas as pd

st.title("🏭 نظام تخصيم مصنع الألوميتال - النسخة الكاملة")

# =========================
# بيانات الوحدة الأساسية
# =========================
عرض = st.text_input("عرض الوحدة (سم)")
ارتفاع = st.text_input("ارتفاع الوحدة (سم)")
عمق = st.text_input("عمق الوحدة (سم)")

# =========================
# إضافات
# =========================
عدد_الرفوف = st.number_input("عدد الرفوف", step=1, value=0)
عدد_الفواصل = st.number_input("عدد الفواصل", step=1, value=0)
عدد_الأدراج = st.number_input("عدد الأدراج", step=1, value=0)

data = []

def add(نوع, وصف, مقاس, عدد):
    data.append([نوع, وصف, مقاس, عدد])

# =========================
# التشغيل
# =========================
if st.button("تشغيل التخصيم"):

    if عرض and ارتفاع and عمق:

        # =========================
        # التخصيم الأساسي
        # =========================
        W = float(عرض)
        H = float(ارتفاع)
        D = float(عمق)

        Wc = W - 5
        Hc = H - 13
        Dc = D - 5

        # =========================
        # 🪵 فيبر الجسم الأساسي
        # =========================
        add("فيبر", "ضهرية", f"{Wc} × {Hc}", 1)
        add("فيبر", "أرضية", f"{Wc} × {Dc}", 1)
        add("فيبر", "أجناب", f"{Hc} × {Dc}", 2)

        # =========================
        # 📚 الرفوف
        # =========================
        if عدد_الرفوف > 0:

            # ألوميتال
            add("ألوميتال", "رف - عرض", 77 * 2, عدد_الرفوف)
            add("ألوميتال", "رف - عمق", 47 * 2, عدد_الرفوف)

            # فيبر (نقص 5 سم)
            add("فيبر", "رف", f"{72 - 5} × {47 - 5}", عدد_الرفوف)

        # =========================
        # 🧱 الفواصل
        # =========================
        if عدد_الفواصل > 0:

            # ألوميتال
            add("ألوميتال", "فاصل - ارتفاع", 77 * 2, عدد_الفواصل)
            add("ألوميتال", "فاصل - عمق", 47 * 2, عدد_الفواصل)

            # فيبر
            add("فيبر", "فاصل", f"{77 - 5} × {47 - 5}", عدد_الفواصل)

        # =========================
        # 🗄️ الأدراج
        # =========================
        if عدد_الأدراج > 0:

            # ألوميتال
            add("ألوميتال", "درج - عرض", 34.5 * 5, عدد_الأدراج)
            add("ألوميتال", "درج - عمق", 45 * 6, عدد_الأدراج)

            # فيبر
            add("فيبر", "درج", "34.5 × 45", عدد_الأدراج)

        # =========================
        # 📊 عرض الجدول
        # =========================
        df = pd.DataFrame(data, columns=["النوع", "الوصف", "المقاس", "العدد"])
        st.dataframe(df)

    else:
        st.error("من فضلك ادخل بيانات الوحدة الأساسية")

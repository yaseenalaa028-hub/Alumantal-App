import streamlit as st

st.title("🏭 نظام التخصيم - مصنع الألوميتال")

# =========================
# بيانات الوحدة
# =========================
عرض = st.number_input("عرض الوحدة (سم)", min_value=0.0)
ارتفاع = st.number_input("ارتفاع الوحدة (سم)", min_value=0.0)
عمق = st.number_input("عمق الوحدة (سم)", min_value=0.0)

# =========================
# الأرفف
# =========================
عرض_الرف = st.number_input("عرض الرف (سم)", min_value=0.0)
عمق_الرف = st.number_input("عمق الرف (سم)", min_value=0.0)
عدد_الأرفف = st.number_input("عدد الأرفف", step=1, value=0)

# =========================
# الفواصل
# =========================
ارتفاع_الفاصل = st.number_input("ارتفاع الفاصل (سم)", min_value=0.0)
عمق_الفاصل = st.number_input("عمق الفاصل (سم)", min_value=0.0)
عدد_الفواصل = st.number_input("عدد الفواصل", step=1, value=0)

# =========================
# الأدراج
# =========================
عرض_الدرج = st.number_input("عرض الدرج (سم)", min_value=0.0)
عمق_الدرج = st.number_input("عمق الدرج (سم)", min_value=0.0)
عدد_الأدراج = st.number_input("عدد الأدراج", step=1, value=0)

# =========================
# تشغيل الحساب
# =========================
if st.button("احسب التخصيم"):

    # ===== التخصيم الأساسي =====
    العرض_الصافي = عرض - 5
    الارتفاع_الصافي = ارتفاع - 13
    العمق_الصافي = عمق - 5

    st.subheader("📌 التخصيم الأساسي")

    st.write("العرض:", العرض_الصافي)
    st.write("الارتفاع:", الارتفاع_الصافي)
    st.write("العمق:", العمق_الصافي)

    # =========================
    # الفيبر
    # =========================
    st.subheader("🪵 الفيبر")

    st.write("الضهرية:", العرض_الصافي, "×", الارتفاع_الصافي)
    st.write("الأرضية:", العرض_الصافي, "×", العمق_الصافي)
    st.write("الأجناب:", الارتفاع_الصافي, "×", العمق_الصافي, "×2")

    # =========================
    # الأرفف
    # =========================
    if عدد_الأرفف > 0:
        عرض_رف_معدل = عرض_الرف - 5
        عمق_رف_معدل = عمق_الرف - 5

        st.subheader("📚 الأرفف")
        st.write("رف فيبر:", عرض_رف_معدل, "×", عمق_رف_معدل, "×", عدد_الأرفف)

    # =========================
    # الفواصل
    # =========================
    if عدد_الفواصل > 0:
        عمق_فاصل_معدل = عمق_الفاصل - 5

        st.subheader("🧱 الفواصل")
        st.write("فاصل فيبر:", ارتفاع_الفاصل, "×", عمق_فاصل_معدل, "×", عدد_الفواصل)

    # =========================
    # الأدراج
    # =========================
    if عدد_الأدراج > 0:
        عرض_درج_معدل = عرض_الدرج - 2.5

        st.subheader("🗄️ الأدراج")
        st.write("درج:", عرض_درج_معدل, "×", عمق_الدرج, "×", عدد_الأدراج)

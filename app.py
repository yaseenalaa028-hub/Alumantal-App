import streamlit as st
import pandas as pd

st.title("🏭 نظام تخصيم مصنع الألوميتال")

# =========================
# بيانات الوحدة
# =========================
عرض = st.text_input("عرض الوحدة (سم)")
ارتفاع = st.text_input("ارتفاع الوحدة (سم)")
عمق = st.text_input("عمق الوحدة (سم)")

# =========================
# الأرفف
# =========================
عرض_الرف = st.text_input("عرض الرف (سم)")
عمق_الرف = st.text_input("عمق الرف (سم)")
عدد_الأرفف = st.text_input("عدد الأرفف")

# =========================
# الفواصل
# =========================
ارتفاع_الفاصل = st.text_input("ارتفاع الفاصل (سم)")
عمق_الفاصل = st.text_input("عمق الفاصل (سم)")
عدد_الفواصل = st.text_input("عدد الفواصل")

# =========================
# الأدراج
# =========================
عرض_الدرج = st.text_input("عرض الدرج (سم)")
عمق_الدرج = st.text_input("عمق الدرج (سم)")
عدد_الأدراج = st.text_input("عدد الأدراج")

# =========================
# زر التشغيل
# =========================
if st.button("تشغيل التخصيم"):

    if عرض and ارتفاع and عمق:

        # التخصيم الأساسي
        W = float(عرض)
        H = float(ارتفاع)
        D = float(عمق)

        Wc = W - 5
        Hc = H - 13
        Dc = D - 5

        data = []

        def add(نوع, وصف, مقاس, عدد):
            data.append([نوع, وصف, مقاس, عدد])

        # =========================
        # الألوميتال الأساسي
        # =========================
        add("ألوميتال", "ارتفاع مفرد", Hc, 2)
        add("ألوميتال", "ارتفاع متقارب", Hc, 2)

        add("ألوميتال", "عرض مفرد", Wc, 3)
        add("ألوميتال", "عرض متقارب", Wc, 1)

        add("ألوميتال", "عمق مفرد", Dc, 2)
        add("ألوميتال", "عمق متقارب", Dc, 2)

        # =========================
        # الفيبر الأساسي
        # =========================
        add("فيبر", "ضهرية", f"{Wc} × {Hc}", 1)
        add("فيبر", "أرضية", f"{Wc} × {Dc}", 1)
        add("فيبر", "أجناب", f"{Hc} × {Dc}", 2)

        # =========================
        # الأرفف
        # =========================
        if عرض_الرف and عمق_الرف and عدد_الأرفف:
            sw = float(عرض_الرف) - 5
            sd = float(عمق_الرف) - 5
            sc = int(عدد_الأرفف)

            add("فيبر", "رف", f"{sw} × {sd}", sc)
            add("ألوميتال", "رف", Hc, sc * 2)

        # =========================
        # الفواصل
        # =========================
        if ارتفاع_الفاصل and عمق_الفاصل and عدد_الفواصل:
            fh = float(ارتفاع_الفاصل)
            fd = float(عمق_الفاصل) - 5
            fc = int(عدد_الفواصل)

            add("فيبر", "فاصل", f"{fh} × {fd}", fc)
            add("ألوميتال", "فاصل", Hc, fc * 2)

        # =========================
        # الأدراج
        # =========================
        if عرض_الدرج and عمق_الدرج and عدد_الأدراج:
            dw = float(عرض_الدرج) - 2.5
            dd = float(عمق_الدرج)
            dc = int(عدد_الأدراج)

            add("فيبر", "درج", f"{dw} × {dd}", dc)

            # ألوميتال الأدراج
            add("ألوميتال", "جانبي درج", Hc, dc * 2)
            add("ألوميتال", "واجهة درج", Wc, dc)

        # =========================
        # عرض الجدول
        # =========================
        df = pd.DataFrame(data, columns=["النوع", "الوصف", "المقاس", "العدد"])
        st.dataframe(df)

    else:
        st.error("من فضلك ادخل بيانات الوحدة الأساسية")
